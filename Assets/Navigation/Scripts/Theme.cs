using UnityEngine;

// The app's colours. The scene builder bakes iris (day) and dusk (night) into the UI, and Settings
// switches between them (ThemeColors); code that colours things at runtime reads Theme.Current.
//   iris    the app's own look: slate indigo (424874) on lavender-white, lavender (DCD6F7), periwinkle
//           (A6B1E1), cool grey (CACFD6) and mint-grey (D6E5E3); a raspberry pin is the one warm colour
//   dusk    iris by night: deep indigo surfaces, periwinkle for the route and buttons
//   campus  light, map-app blue on white, green guidance banner (the first look; -theme campus)
//   paper   warm off-white, ink and vermilion, like a printed building directory (previews only)
//   knight  black and UCF gold (the first night look)
// The older three stay because the builder takes -theme, and the basemap, logo and icons are made for them.
public class Theme
{
    public string name;

    // Surfaces and text
    public Color surface, surfaceVariant, onSurface, onSurfaceVariant, outline, inverseSurface, onInverseSurface;

    // The route, buttons and selection
    public Color primary, onPrimary, primaryContainer, routeCasing;

    // The turn-by-turn banner
    public Color banner, bannerDark, onBanner;

    // Status
    public Color destination, onDestination, good, warning, error;

    // The floor map: the ground around the building, room numbers, and the place icons' discs
    public Color mapGround, mapLabel, mapLabelHalo, room, restroom, elevator, stairs, exit, onPlace;

    // Walls on the tilted map
    public Color wallTop, wallSide;

    // Campus: the ground's layers in CampusData order (campus, grass, sports, trees, sand, paved, water,
    // paths, road casing, major road casing, roads, major roads), then the buildings' roofs and walls.
    public Color[] campusLayers;
    public Color buildingTop, buildingSide;

    // The soft shadow under cards over the map (UI/Shadow.png tinted). Clear: no shadows, the older themes' look.
    public Color shadow;

    // The route on the floor in AR, and the glow round its edges (its alpha is how strong). Clear: the primary
    // colour, with no glow (the older themes' look). The turn banner's arrow tile takes the same colour.
    public Color ribbon, ribbonGlow;
    public Color Ribbon => ribbon.a > 0f ? ribbon : primary;
    public Color RibbonChevron => ribbon.a > 0f ? Color.white : onPrimary;

